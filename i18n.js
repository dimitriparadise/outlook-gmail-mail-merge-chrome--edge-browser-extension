let uiLanguage = 'en';

function detectUiLanguage(languages) {
  const list = languages ?? (typeof navigator !== 'undefined' ? navigator.languages || [navigator.language] : []);
  for (const lang of list || []) {
    const code = String(lang || '').toLowerCase().split('-')[0];
    if (UI_LANGUAGES.includes(code)) return code;
  }
  return 'en';
}

function setUiLanguage(lang) {
  uiLanguage = UI_LANGUAGES.includes(lang) ? lang : 'en';
  return uiLanguage;
}

function uiLocale() {
  return { en: 'en-US', zh: 'zh-CN', es: 'es' }[uiLanguage] || 'en-US';
}

function t(key, vars = {}) {
  const template = UI_STRINGS[uiLanguage]?.[key] ?? UI_STRINGS.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
}

// Elements opt in with data-i18n (text), data-i18n-placeholder, data-i18n-title, or data-i18n-empty.
function applyStaticTranslations(root = typeof document !== 'undefined' ? document : null) {
  if (!root?.querySelectorAll) return;
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll('[data-i18n-empty]').forEach(el => { el.dataset.empty = t(el.dataset.i18nEmpty); });
  if (root.documentElement) root.documentElement.lang = uiLanguage === 'zh' ? 'zh-CN' : uiLanguage;
}
